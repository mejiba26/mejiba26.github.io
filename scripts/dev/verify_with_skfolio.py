"""
Independent check of the v2 optimizers against skfolio. LOCAL USE ONLY, never run in a workflow.

    pip install skfolio==1.14.4 pandas==3.1.1 numpy==2.5.4    # skfolio brings scikit-learn, scipy, cvxpy
    python scripts/dev/verify_with_skfolio.py

On 14 fixed months (12 evenly spaced inside the out of sample period plus the first and last) it fits
Min Variance, Max Sharpe (40% cap) and risk parity with each covariance estimator, in both
scripts/portfolio_model.py and skfolio (convex solver, Clarabel), and writes the largest absolute
weight difference per case to docs/portfolio-verification.md. Reads data/portfolio/prices.csv only.
"""
import sys
from importlib.metadata import version
from pathlib import Path

import numpy as np
import pandas as pd
from skfolio import RiskMeasure
from skfolio.moments import EmpiricalCovariance, EmpiricalMu, EWCovariance, LedoitWolf
from skfolio.optimization import MeanRisk, ObjectiveFunction, RiskBudgeting
from skfolio.prior import EmpiricalPrior

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import portfolio_model as P  # noqa: E402

SKFOLIO_VERSION = "1.14.4"
TOL = 0.005          # max absolute weight difference (half a percentage point)
DOC = P.ROOT / "docs" / "portfolio-verification.md"

SK_COV = {"Sample": lambda: EmpiricalCovariance(ddof=1),
          "LW": lambda: LedoitWolf(),
          "EWMA": lambda: EWCovariance(half_life=P.HALF_LIFE, assume_centered=False)}


def centered_like_v2(hist):
    """Control for the EWMA definitional difference: subtract v2's single window weighted mean first."""
    w = 0.5 ** (np.arange(len(hist))[::-1] / P.HALF_LIFE)
    return hist - (w / w.sum()) @ hist.values


def sk_weights(rule, est, hist, rf_hist):
    if est == "EWMA*":
        hist, est = centered_like_v2(hist), "EWMA0"
    cov = EWCovariance(half_life=P.HALF_LIFE, assume_centered=True) if est == "EWMA0" else SK_COV[est]()
    prior = EmpiricalPrior(mu_estimator=EmpiricalMu(), covariance_estimator=cov)
    if rule == "MV":
        m = MeanRisk(objective_function=ObjectiveFunction.MINIMIZE_RISK, risk_measure=RiskMeasure.VARIANCE,
                     prior_estimator=prior, min_weights=0, max_weights=1)
    elif rule == "MS":
        # Mean of (r - rf) = mean(r) - mean(rf) and weights sum to 1, so a constant rf equal to the
        # window's mean rf gives exactly v1's excess return objective.
        m = MeanRisk(objective_function=ObjectiveFunction.MAXIMIZE_RATIO, risk_measure=RiskMeasure.STANDARD_DEVIATION,
                     risk_free_rate=float(rf_hist.mean()), prior_estimator=prior, min_weights=0, max_weights=P.MAX_WEIGHT)
    else:
        m = RiskBudgeting(risk_measure=RiskMeasure.VARIANCE, prior_estimator=prior, min_weights=0, max_weights=1)
    return m.fit(hist).weights_


def main():
    if version("skfolio") != SKFOLIO_VERSION:
        sys.exit(f"Expected skfolio {SKFOLIO_VERSION}, found {version('skfolio')}")
    prices = pd.read_csv(P.OUT / "prices.csv", index_col=0, parse_dates=True)
    rets, rf = P.monthly_returns(prices, drop_partial=False)
    oos = np.arange(P.LOOKBACK, len(rets))
    picks = oos[np.linspace(0, len(oos) - 1, 14).round().astype(int)]

    rows, worst = [], {}
    for i in picks:
        hist, rf_hist = rets.iloc[i - P.LOOKBACK:i], rf.iloc[i - P.LOOKBACK:i]
        row = {"month": f"{rets.index[i]:%Y-%m}"}
        for rule, rfn in P.RULES.items():
            for est, efn in P.ESTIMATORS.items():
                mine, _ = rfn(hist, rf_hist, efn(hist))
                d = float(np.abs(mine - sk_weights(rule, est, hist, rf_hist)).max())
                row[f"{rule}-{est}"] = d
                worst[f"{rule}-{est}"] = max(worst.get(f"{rule}-{est}", 0), d)
        for rule in ("MV", "RP"):                  # MS cannot use the control: centering removes the mean
            mine, _ = P.RULES[rule](hist, rf_hist, P.cov_ewma(hist))
            d = float(np.abs(mine - sk_weights(rule, "EWMA*", hist, rf_hist)).max())
            row[f"{rule}-EWMA*"] = d
            worst[f"{rule}-EWMA*"] = max(worst.get(f"{rule}-EWMA*", 0), d)
        rows.append(row)
    df = pd.DataFrame(rows).set_index("month")

    cols = list(df.columns)
    lines = ["| Month | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for m, r in df.iterrows():
        lines.append(f"| {m} | " + " | ".join(f"{v:.4f}" + ("" if v <= TOL else " ✗") for v in r) + " |")
    lines.append("| **Worst** | " + " | ".join(f"**{worst[c]:.4f}**" for c in cols) + " |")
    passed = [c for c in cols if worst[c] <= TOL and "*" not in c]
    ewma_ctl = ", ".join(f"{c} {worst[c]:.4f}" for c in cols if "*" in c)

    DOC.write_text(f"""# Portfolio model v2: independent verification against skfolio

Generated by `scripts/dev/verify_with_skfolio.py` (local only, not part of any workflow) with skfolio {SKFOLIO_VERSION}, on `data/portfolio/prices.csv`.

Each cell is the largest absolute difference between one ETF's weight in `scripts/portfolio_model.py` and in skfolio, for the month shown (weights set from the 36 months before it). Tolerance: {TOL} (half a percentage point). ✗ marks a cell above it. Months: 12 evenly spaced in the out of sample period plus the first and last.

{chr(10).join(lines)}

Within tolerance in every month: {len(passed)} of 9 cases ({", ".join(passed) or "none"}).

Columns marked * are a control, not one of the nine cases: skfolio is given returns already centered on v2's single window weighted mean, with `EWCovariance(half_life=12, assume_centered=True)`. Worst differences in the control: {ewma_ctl}. If these are near zero, the EWMA gap above comes from the centering definition below, not from an error in v2. (Max Sharpe cannot use the control, because centering the returns removes the expected returns it needs.)

## How the two sides are matched, and where they differ by definition

- **Optimizers.** v2 uses SciPy SLSQP (v1's settings) for MV and MS and a log barrier with L-BFGS-B for RP. skfolio solves the same problems as convex programs (Clarabel through cvxpy), and Max Sharpe through the standard change of variables, so it finds the global optimum. Agreement here checks v2's optimizer and constraints.
- **Max Sharpe objective.** v1 uses the mean of (return − risk free) over the window. skfolio gets the raw mean return and a constant risk free rate equal to the window's mean risk free rate. Because the weights sum to 1, the two objectives are identical.
- **Sample (E1).** skfolio `EmpiricalCovariance(ddof=1)` equals pandas `.cov()`. Independent.
- **Ledoit-Wolf (E2).** skfolio's `LedoitWolf` wraps scikit-learn's, which v2 also uses, so this column checks the optimizers only, not the estimator.
- **EWMA (E3), a definitional difference.** v2 (spec E3) subtracts one exponentially weighted mean over the whole 36 month window, then takes the weighted average of the outer products. skfolio's `EWCovariance(half_life=12, assume_centered=False)` updates step by step, subtracting a running weighted mean that starts at zero, and rescales for the short history. The decay (half life 12) is the same, and the centering is not, so small differences in the EWMA columns are expected and are not forced to zero.
""", encoding="utf-8")
    print(df.round(4).to_string())
    print(f"\nWorst: {dict((k, round(v, 4)) for k, v in worst.items())}\nWrote {DOC}")


if __name__ == "__main__":
    main()
